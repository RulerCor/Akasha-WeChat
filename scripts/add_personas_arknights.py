def main() -> int:
    c = sqlite3.connect(DB)
    existing = {r[0] for r in c.execute("select persona_id from personas")}
    print("现有 personas:", sorted(existing))
    added, skipped = [], []
    for pid, data in PERSONAS.items():
        if pid in existing:
            skipped.append(pid)
            continue
        c.execute(
            "insert into personas (created_at, updated_at, persona_id, "
            "system_prompt, begin_dialogs, tools, skills, custom_error_message, "
            "folder_id, sort_order) "
            "values (datetime('now'), datetime('now'), ?, ?, '[]', null, null, null, null, 0)",
            (pid, data["prompt"]),
        )
        added.append(pid)
    c.commit()

    # 备份全部 prompt 文本
    os.makedirs(BACKUP_DIR, exist_ok=True)
    for pid in added:
        sp = c.execute("select system_prompt from personas where persona_id=?", (pid,)).fetchone()[0]
        p = os.path.join(BACKUP_DIR, f"persona_{pid}_{datetime.now():%Y%m%d_%H%M%S}.txt")
        io.open(p, "w", encoding="utf-8", newline="\n").write(sp)
        print(f"  已备份 → {os.path.basename(p)}")
    c.close()

    if added:
        print(f"✅ 新增 {len(added)} 个人格: {', '.join(added)}")
        print("   ⚠️ 人设只在 AstrBot 启动时读入内存——需重启才生效")
    if skipped:
        print(f"   跳过（已存在）: {', '.join(skipped)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

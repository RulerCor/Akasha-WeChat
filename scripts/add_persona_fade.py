def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--verify", action="store_true")
    args = ap.parse_args()

    c = sqlite3.connect(DB)
    row = c.execute(
        "select system_prompt from personas where persona_id='fade'"
    ).fetchone()

    if args.verify:
        if not row:
            print("❌ 人格 fade 不存在")
            return 1
        missing = [m for m in MARKS if m not in row[0]]
        print(f"fade 存在，prompt {len(row[0])} 字")
        if missing:
            print("❌ 缺段落:", missing)
            return 1
        print("✅ 全部必需段落齐全")
        return 0

    if row:
        print("⏭️  人格 fade 已存在，跳过")
        c.close()
        return 0

    c.execute(
        "insert into personas (created_at, updated_at, persona_id, "
        "system_prompt, begin_dialogs, tools, skills, custom_error_message, "
        "folder_id, sort_order) "
        "values (datetime('now'), datetime('now'), 'fade', ?, '[]', null, "
        "null, null, null, 0)",
        (FADE_PROMPT,),
    )
    c.commit()

    os.makedirs(BACKUP_DIR, exist_ok=True)
    p = os.path.join(BACKUP_DIR, f"persona_fade_{datetime.now():%Y%m%d_%H%M%S}.txt")
    io.open(p, "w", encoding="utf-8", newline="\n").write(FADE_PROMPT)
    c.close()
    print(f"✅ 已新增人格 fade（黑梦），prompt {len(FADE_PROMPT)} 字")
    print(f"   已备份 → {os.path.basename(p)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
